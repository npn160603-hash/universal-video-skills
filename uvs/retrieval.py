"""Text retrieval of local media for script scenes (Phase 3).

Lexical and explainable, not semantic. A query (a scene's words) is matched against each asset's
sidecar tags (weight 3), description (weight 2) and file name (weight 1). A query term matches a
term in those fields exactly (full weight) or through a small hand-written synonym group (60 % of
the weight). Terms are weighted by inverse document frequency, so a rare word counts for more
than a common one.

Scores run from 0 to 1. A score of 1 means every query term matched a tag exactly. Results below
min_score are dropped, and the output lists which terms were matched and which were missing.
There are no embeddings, so a word with no listed synonym does not match.

Scenes whose visual is generated by the renderer (charts, graphics, map, text, negative space)
are not given footage.

CLI:
    python3 -m uvs.retrieval <folder> --query "enrollment grew" [--count 5] [--cache DIR]
    python3 -m uvs.retrieval <folder> --plan plan.json [--out assignments.json] [--require-licence]
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from uvs import media_index as M
from uvs.narrative import STOPWORDS

FIELD_WEIGHTS = {"tags": 3.0, "description": 2.0, "name": 1.0}
MAX_WEIGHT = max(FIELD_WEIGHTS.values())
SYNONYM_FACTOR = 0.6
DEFAULT_MIN_SCORE = 0.3
GENERATED_VISUALS = {"chart", "graphics", "text_emphasis", "negative_space", "map"}

# Hand-written. Each group lists words that may stand for each other. Extend it when a real
# library needs it; this list is not exhaustive.
SYNONYM_GROUPS = [
    {"city", "urban", "street", "skyline", "town", "metropolis"},
    {"money", "cash", "dollar", "currency", "finance", "bank", "wealth"},
    {"growth", "rise", "increase", "grow", "expansion", "surge"},
    {"decline", "fall", "drop", "decrease", "shrink", "collapse"},
    {"school", "student", "classroom", "campus", "education", "university"},
    {"night", "dark", "darkness", "evening"},
    {"ocean", "sea", "water", "waves", "coast"},
    {"crowd", "people", "queue", "audience", "public"},
    {"factory", "plant", "industrial", "manufacturing", "production"},
    {"map", "globe", "route", "geography"},
    {"doctor", "hospital", "clinic", "medical", "health"},
    {"car", "vehicle", "automobile", "traffic", "road"},
    {"computer", "laptop", "screen", "code"},
    {"grief", "mourning", "funeral", "sorrow"},
]
_GROUP_OF: dict[str, set[str]] = {}
for _g in SYNONYM_GROUPS:
    for _w in _g:
        _GROUP_OF.setdefault(_w, set()).update(_g)


@dataclass
class Hit:
    asset: M.Asset
    score: float
    matched: list[str] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"path": self.asset.path, "kind": self.asset.kind, "score": round(self.score, 3),
                "matched": self.matched, "missing": self.missing,
                "license": self.asset.provenance.get("license", "unknown")}


def _norm(token: str) -> str:
    t = token.lower()
    if len(t) > 4 and t.endswith("ies"):
        return t[:-3] + "y"
    if len(t) > 3 and t.endswith("s") and not t.endswith("ss"):
        return t[:-1]
    return t


_WORD = re.compile(r"[^\W_]+")  # letters and digits; underscores and hyphens split words


def terms(text: str) -> set[str]:
    """Normalised content words. Unicode-aware, so Vietnamese words stay whole."""
    return {_norm(t) for t in _WORD.findall(text) if t.lower() not in STOPWORDS and len(t) > 1}


def _query_terms(query: str) -> list[str]:
    seen: list[str] = []
    for t in _WORD.findall(query):
        n = _norm(t)
        if t.lower() in STOPWORDS or len(t) <= 1 or n in seen:
            continue
        seen.append(n)
    return seen


def _doc_fields(a: M.Asset) -> dict[str, set[str]]:
    return {"tags": terms(" ".join(a.tags)),
            "description": terms(a.description),
            "name": terms(Path(a.path).stem)}


def _match(q: str, fields: dict[str, set[str]]) -> tuple[float, str | None]:
    """Best field match for one query term. Returns (weight, label) or (0, None)."""
    expansions = _GROUP_OF.get(q, set()) - {q}
    best: tuple[float, str | None] = (0.0, None)
    for fname, weight in FIELD_WEIGHTS.items():
        pool = fields[fname]
        if q in pool:
            cand = (weight, f"{fname}:{q}")
        elif pool & expansions:
            word = sorted(pool & expansions)[0]
            cand = (weight * SYNONYM_FACTOR, f"{fname}:{word} (synonym of {q})")
        else:
            continue
        if cand[0] > best[0]:
            best = cand
    return best


def _known_licence(a: M.Asset) -> bool:
    return a.provenance.get("license", "unknown") != "unknown"


def search(assets: list[M.Asset], query: str, *, count: int = 5, kind: str | None = None,
           require_known_licence: bool = False, min_score: float = DEFAULT_MIN_SCORE,
           exclude: frozenset[str] = frozenset()) -> list[Hit]:
    """Rank assets for a text query. Skips visual near-duplicates within the result."""
    qterms = _query_terms(query)
    if not qterms:
        return []
    pool = [a for a in assets
            if (kind is None or a.kind == kind)
            and a.path not in exclude
            and (not require_known_licence or _known_licence(a))]
    if not pool:
        return []
    fields = {a.path: _doc_fields(a) for a in pool}
    matches: dict[str, dict[str, tuple[float, str]]] = {a.path: {} for a in pool}
    df = {q: 0 for q in qterms}
    for a in pool:
        for q in qterms:
            w, label = _match(q, fields[a.path])
            if w:
                matches[a.path][q] = (w, label)
                df[q] += 1
    n = len(pool)
    idf = {q: math.log(1 + n / (1 + df[q])) for q in qterms}
    denom = sum(idf[q] * MAX_WEIGHT for q in qterms)

    hits: list[Hit] = []
    for a in pool:
        m = matches[a.path]
        raw = sum(idf[q] * m[q][0] for q in m)
        score = raw / denom if denom else 0.0
        if score < min_score:
            continue
        hits.append(Hit(asset=a, score=score,
                        matched=[m[q][1] for q in qterms if q in m],
                        missing=[q for q in qterms if q not in m]))
    hits.sort(key=lambda h: (-h.score, h.asset.path))

    chosen: list[Hit] = []
    for h in hits:
        if len(chosen) >= count:
            break
        if any(c.asset.sha256 == h.asset.sha256 for c in chosen):
            continue
        if h.asset.dhash and any(c.asset.dhash and M.hamming(h.asset.dhash, c.asset.dhash) <= 5
                                 for c in chosen):
            continue
        chosen.append(h)
    return chosen


def plan_broll(plan: dict, assets: list[M.Asset], *, require_known_licence: bool = False,
               min_score: float = DEFAULT_MIN_SCORE) -> dict:
    """Assign footage to each scene of a narrative plan. Each asset is used at most once."""
    used: dict[str, str] = {}
    rows = []
    for scene in plan.get("scenes", []):
        visual = scene.get("visual")
        text = scene.get("text", "")
        row = {"scene": scene.get("id"), "visual": visual, "query": text}
        if visual in GENERATED_VISUALS:
            row.update(status="generated", path=None, score=None, matched=[], missing=[],
                       reason=f"{visual} is drawn by the renderer, not taken from footage")
        elif not _query_terms(text):
            row.update(status="unfilled", path=None, score=None, matched=[], missing=[],
                       reason="scene text has no content words to match")
        else:
            hits = search(assets, text, count=1, require_known_licence=require_known_licence,
                          min_score=min_score, exclude=frozenset(used))
            if hits:
                h = hits[0]
                used[h.asset.path] = str(scene.get("id"))
                row.update(status="matched", path=h.asset.path, score=round(h.score, 3),
                           matched=h.matched, missing=h.missing, reason=None)
            else:
                blocked = search(assets, text, count=1, require_known_licence=require_known_licence,
                                 min_score=min_score)
                if blocked and blocked[0].asset.path in used:
                    reason = f"best match is already used in scene {used[blocked[0].asset.path]}"
                else:
                    reason = "no asset reaches the minimum score"
                row.update(status="unfilled", path=None, score=None, matched=[], missing=[],
                           reason=reason)
        rows.append(row)
    counts = {s: sum(1 for r in rows if r["status"] == s) for s in ("matched", "unfilled", "generated")}
    return {"min_score": min_score, "require_known_licence": require_known_licence,
            "scenes": rows, "counts": counts}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Retrieve local media for a query or a narrative plan.")
    ap.add_argument("folder")
    ap.add_argument("--query")
    ap.add_argument("--plan")
    ap.add_argument("--count", type=int, default=5)
    ap.add_argument("--kind", choices=["image", "video", "audio"])
    ap.add_argument("--cache")
    ap.add_argument("--require-licence", action="store_true")
    ap.add_argument("--min-score", type=float, default=DEFAULT_MIN_SCORE)
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    if bool(args.query) == bool(args.plan):
        ap.error("give exactly one of --query or --plan")
    assets = M.scan(args.folder, args.cache)
    if args.query:
        result: dict = {"query": args.query,
                        "hits": [h.to_dict() for h in search(
                            assets, args.query, count=args.count, kind=args.kind,
                            require_known_licence=args.require_licence, min_score=args.min_score)]}
    else:
        plan = json.loads(Path(args.plan).read_text(encoding="utf-8"))
        result = plan_broll(plan, assets, require_known_licence=args.require_licence,
                            min_score=args.min_score)
    text = json.dumps(result, ensure_ascii=False, indent=2)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
